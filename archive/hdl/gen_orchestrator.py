#!/usr/bin/env python3
"""Generate orchestrator.v (one parameterized SoC) + the four thin wrappers.

The four orchestrator SoC variants (chip / mcu / sbc / sbc_moe) are folded
into one module selected by the ROLE parameter.  Each role's body is spliced
verbatim (with mechanical renames) into a NAMED generate block so the
duplicate localparams/locals stay scoped.  The original module names become
thin wrappers so testbenches and boards are unchanged.

Run from this directory:  python3 gen_orchestrator.py
"""
import os
import re
import subprocess

HERE = os.path.dirname(os.path.abspath(__file__))

ROLES = [
    ("CHIP", "orchestrator_chip.v"),
    ("MCU", "orchestrator_mcu.v"),
    ("SBC", "orchestrator_sbc.v"),
    ("SBC_MOE", "orchestrator_sbc_moe.v"),
]

# chip declares these outputs `reg` and drives them procedurally; the unified
# module declares them `wire`, so the chip role drives internal regs instead.
CHIP_REGS = ["pcie_out_data", "pcie_out_valid", "pcie_out_sop", "pcie_out_eop",
             "boot_done", "dispatches", "weight_flits", "errors"]


def body_of(src):
    # Read the ORIGINAL variant from git HEAD, not the working tree: this
    # script overwrites that very file with a thin wrapper, so a second run
    # would otherwise splice the wrapper into itself (infinite recursion).
    try:
        text = subprocess.check_output(
            ["git", "-C", HERE, "show", "HEAD:HDL/" + src],
            stderr=subprocess.DEVNULL).decode()
    except Exception:
        text = open(os.path.join(HERE, src)).read()
    m = re.search(r"\n\);\s*\n", text)      # port list closes ');' on its own line
    body = text[m.end():]
    body = body[:body.rindex("endmodule")]
    return body.strip("\n")


def role_body(name, src):
    b = body_of(src)
    b = re.sub(r"\n\s*function \[15:0\] crc16_next;.*?endfunction\n", "\n",
               b, flags=re.S)
    if name == "CHIP":
        for p in CHIP_REGS:
            b = re.sub(r"\b%s\b" % p, p + "_r", b)
    return b


UNION_PARAMS = [
    ("ROLE", "0"),
    ("CLK_FREQ", "100_000_000"),
    ("BAUD_RATE", "115200"),
    ("NUM_LAYERS", "8"),
    ("BOARD_X", "8"),
    ("BOARD_Y", "8"),
    ("NUM_NODES", "NUM_LAYERS * BOARD_X * BOARD_Y"),
    ("MAX_EXPERTS", "128"),
    ("TOP_K", "8"),
    ("HIDDEN_SIZE", "2816"),
    ("VENDOR_ID", "16'h4D50"),
    ("DRAM_WORDS", "1048576"),
    ("DRAM_LATENCY", "4"),
    ("SRAM_WORDS", "131072"),
    ("GATING_ENTRIES", "32768"),
    ("ARRAY_SIZE", "16"),
]


def gen_orchestrator():
    o = []
    o.append("`timescale 1ns/1ps")
    o.append("")
    o.append("// =============================================================================")
    o.append("// orchestrator — the PNM SoC family as one parameterized module")
    o.append("//")
    o.append("// ROLE selects the class:  0 = CHIP  (PCIe router chip, MoE dispatch)")
    o.append("//                          1 = MCU   (bare-metal RV32I + UART)")
    o.append("//                          2 = SBC   (RV32IMA + DRAM + PCIe + NVMe)")
    o.append("//                          3 = SBC_MOE (SBC + on-die MoE gating SRAM)")
    o.append("// The four legacy module names are thin wrappers around this module.")
    o.append("// Generated by gen_orchestrator.py — edit the source variants, not this.")
    o.append("// =============================================================================")
    o.append("module orchestrator #(")
    for i, (n, d) in enumerate(UNION_PARAMS):
        sep = "," if i < len(UNION_PARAMS) - 1 else ""
        o.append("    parameter %-14s = %s%s" % (n, d, sep))
    o.append(")(")
    o.append("    input  wire        clk,")
    o.append("    input  wire        rst_n,")
    o.append("    // UART console (MCU/SBC/SBC_MOE)")
    o.append("    input  wire        uart_rx,")
    o.append("    output wire        uart_tx,")
    o.append("    // PCIe (CHIP/SBC_MOE)")
    o.append("    input  wire [7:0]  pcie_in_data,")
    o.append("    input  wire        pcie_in_valid,")
    o.append("    input  wire        pcie_in_sop,")
    o.append("    input  wire        pcie_in_eop,")
    o.append("    output wire        pcie_in_ready,")
    o.append("    output wire [7:0]  pcie_out_data,")
    o.append("    output wire        pcie_out_valid,")
    o.append("    output wire        pcie_out_sop,")
    o.append("    output wire        pcie_out_eop,")
    o.append("    input  wire        pcie_out_ready,")
    o.append("    // POST discovery sideband")
    o.append("    input  wire [NUM_NODES-1:0] topology_rdy,")
    o.append("    // Spine injection")
    o.append("    output wire [7:0]  spine_inject_data,")
    o.append("    output wire        spine_inject_valid,")
    o.append("    output wire        spine_inject_sop,")
    o.append("    output wire        spine_inject_eop,")
    o.append("    input  wire        spine_inject_ready,")
    o.append("    output wire [1:0]  spine_inject_vc,")
    o.append("    // Spine extraction")
    o.append("    input  wire [7:0]  spine_extract_data,")
    o.append("    input  wire        spine_extract_valid,")
    o.append("    input  wire        spine_extract_sop,")
    o.append("    input  wire        spine_extract_eop,")
    o.append("    input  wire [1:0]  spine_extract_vc,")
    o.append("    // External interrupts (MCU uses [7:0]; SBC/SBC_MOE [15:0])")
    o.append("    input  wire [15:0] ext_irq,")
    o.append("    // Status (CHIP)")
    o.append("    output wire        boot_done,")
    o.append("    output wire [31:0] dispatches,")
    o.append("    output wire [31:0] weight_flits,")
    o.append("    output wire [31:0] errors")
    o.append(");")
    o.append("")
    o.append("    localparam ROLE_CHIP    = 0;")
    o.append("    localparam ROLE_MCU     = 1;")
    o.append("    localparam ROLE_SBC     = 2;")
    o.append("    localparam ROLE_SBC_MOE = 3;")
    o.append("")
    o.append("    function [15:0] crc16_next;")
    o.append("        input [15:0] crc_in;")
    o.append("        input [7:0]  data_in;")
    o.append("        reg [15:0] crc;")
    o.append("        integer i;")
    o.append("        begin")
    o.append("            crc = crc_in ^ {data_in, 8'h00};")
    o.append("            for (i = 0; i < 8; i = i + 1) begin")
    o.append("                if (crc[15]) crc = (crc << 1) ^ 16'h1021;")
    o.append("                else         crc = crc << 1;")
    o.append("            end")
    o.append("            crc16_next = crc;")
    o.append("        end")
    o.append("    endfunction")
    o.append("")
    o.append("    generate")
    for name, src in ROLES:
        b = role_body(name, src)
        o.append("        if (ROLE == ROLE_%s) begin : g_%s" % (name, name.lower()))
        if name == "CHIP":
            o.append("            // these were `output reg` ports; now internal")
            o.append("            reg [7:0]  pcie_out_data_r;")
            o.append("            reg        pcie_out_valid_r, pcie_out_sop_r, pcie_out_eop_r;")
            o.append("            reg        boot_done_r;")
            o.append("            reg [31:0] dispatches_r, weight_flits_r, errors_r;")
        o.append("\n".join(("            " + ln) if ln.strip() else ln
                           for ln in b.splitlines()))
        if name == "CHIP":
            o.append("            assign boot_done    = boot_done_r;")
            o.append("            assign dispatches   = dispatches_r;")
            o.append("            assign weight_flits = weight_flits_r;")
            o.append("            assign errors       = errors_r;")
            o.append("            assign pcie_out_data  = pcie_out_data_r;")
            o.append("            assign pcie_out_valid = pcie_out_valid_r;")
            o.append("            assign pcie_out_sop   = pcie_out_sop_r;")
            o.append("            assign pcie_out_eop   = pcie_out_eop_r;")
        o.append("        end")
        o.append("")
    o.append("    endgenerate")
    o.append("")
    o.append("endmodule")
    return "\n".join(o) + "\n"


def wrapper_chip():
    return (
        "`timescale 1ns/1ps\n"
        "// orchestrator_chip — thin wrapper over the parameterized orchestrator.\n"
        "// Generated by gen_orchestrator.py.\n"
        "module orchestrator_chip #(\n"
        "    parameter NUM_LAYERS   = 4,\n"
        "    parameter BOARD_X      = 4,\n"
        "    parameter BOARD_Y      = 4,\n"
        "    parameter NUM_NODES    = NUM_LAYERS * BOARD_X * BOARD_Y,\n"
        "    parameter MAX_EXPERTS  = 128,\n"
        "    parameter TOP_K        = 8,\n"
        "    parameter HIDDEN_SIZE  = 2816,\n"
        "    parameter VENDOR_ID    = 16'h4D50\n"
        ") (\n"
        "    input  wire        clk,\n"
        "    input  wire        rst_n,\n"
        "    input  wire [7:0]  pcie_in_data,\n"
        "    input  wire        pcie_in_valid,\n"
        "    input  wire        pcie_in_sop,\n"
        "    input  wire        pcie_in_eop,\n"
        "    output wire        pcie_in_ready,\n"
        "    output wire [7:0]  pcie_out_data,\n"
        "    output wire        pcie_out_valid,\n"
        "    output wire        pcie_out_sop,\n"
        "    output wire        pcie_out_eop,\n"
        "    input  wire        pcie_out_ready,\n"
        "    output wire [7:0]  spine_inject_data,\n"
        "    output wire        spine_inject_valid,\n"
        "    output wire        spine_inject_sop,\n"
        "    output wire        spine_inject_eop,\n"
        "    input  wire        spine_inject_ready,\n"
        "    output wire [1:0]  spine_inject_vc,\n"
        "    input  wire [7:0]  spine_extract_data,\n"
        "    input  wire        spine_extract_valid,\n"
        "    input  wire        spine_extract_sop,\n"
        "    input  wire        spine_extract_eop,\n"
        "    input  wire [1:0]  spine_extract_vc,\n"
        "    input  wire [NUM_NODES-1:0] topology_rdy,\n"
        "    output wire        boot_done,\n"
        "    output wire [31:0] dispatches,\n"
        "    output wire [31:0] weight_flits,\n"
        "    output wire [31:0] errors\n"
        ");\n"
        "    orchestrator #(.ROLE(0), .NUM_LAYERS(NUM_LAYERS), .BOARD_X(BOARD_X),\n"
        "        .BOARD_Y(BOARD_Y), .NUM_NODES(NUM_NODES), .MAX_EXPERTS(MAX_EXPERTS),\n"
        "        .TOP_K(TOP_K), .HIDDEN_SIZE(HIDDEN_SIZE), .VENDOR_ID(VENDOR_ID)) u (\n"
        "        .clk(clk), .rst_n(rst_n), .uart_rx(1'b0), .uart_tx(),\n"
        + PCIE_CONN +
        "        .topology_rdy(topology_rdy),\n" + SPINE_CONN +
        "        .ext_irq(16'h0),\n"
        "        .boot_done(boot_done), .dispatches(dispatches),\n"
        "        .weight_flits(weight_flits), .errors(errors));\n"
        "endmodule\n")


SPINE_CONN = (
    "        .spine_inject_data(spine_inject_data),\n"
    "        .spine_inject_valid(spine_inject_valid),\n"
    "        .spine_inject_sop(spine_inject_sop),\n"
    "        .spine_inject_eop(spine_inject_eop),\n"
    "        .spine_inject_ready(spine_inject_ready),\n"
    "        .spine_inject_vc(spine_inject_vc),\n"
    "        .spine_extract_data(spine_extract_data),\n"
    "        .spine_extract_valid(spine_extract_valid),\n"
    "        .spine_extract_sop(spine_extract_sop),\n"
    "        .spine_extract_eop(spine_extract_eop),\n"
    "        .spine_extract_vc(spine_extract_vc),\n")

PCIE_CONN = (
    "        .pcie_in_data(pcie_in_data), .pcie_in_valid(pcie_in_valid),\n"
    "        .pcie_in_sop(pcie_in_sop), .pcie_in_eop(pcie_in_eop),\n"
    "        .pcie_in_ready(pcie_in_ready), .pcie_out_data(pcie_out_data),\n"
    "        .pcie_out_valid(pcie_out_valid), .pcie_out_sop(pcie_out_sop),\n"
    "        .pcie_out_eop(pcie_out_eop), .pcie_out_ready(pcie_out_ready),\n")

PCIE_TIE = (
    "        .pcie_in_data(8'h0), .pcie_in_valid(1'b0),\n"
    "        .pcie_in_sop(1'b0), .pcie_in_eop(1'b0),\n"
    "        .pcie_in_ready(), .pcie_out_data(), .pcie_out_valid(),\n"
    "        .pcie_out_sop(), .pcie_out_eop(), .pcie_out_ready(1'b0),\n")


def wrapper_soc(mod, role, params_decl, params_conn, pcie, irq_width):
    pcie_ports = (
        "    input  wire [7:0]  pcie_in_data,\n"
        "    input  wire        pcie_in_valid,\n"
        "    input  wire        pcie_in_sop,\n"
        "    input  wire        pcie_in_eop,\n"
        "    output wire        pcie_in_ready,\n"
        "    output wire [7:0]  pcie_out_data,\n"
        "    output wire        pcie_out_valid,\n"
        "    output wire        pcie_out_sop,\n"
        "    output wire        pcie_out_eop,\n"
        "    input  wire        pcie_out_ready,\n") if pcie else ""
    irq_port = "    input  wire %s ext_irq,\n" % irq_width
    irq_conn = ".ext_irq({8'h0, ext_irq})," if irq_width == "[7:0]" else ".ext_irq(ext_irq),"
    s = "`timescale 1ns/1ps\n"
    s += "// %s — thin wrapper over the parameterized orchestrator.\n" % mod
    s += "// Generated by gen_orchestrator.py.\n"
    s += "module %s #(\n" % mod
    s += params_decl
    s += ")(\n"
    s += "    input  wire        clk,\n"
    s += "    input  wire        rst_n,\n"
    s += "    input  wire        uart_rx,\n"
    s += "    output wire        uart_tx,\n"
    s += pcie_ports
    s += "    input  wire [NUM_NODES-1:0] topology_rdy,\n"
    s += "    output wire [7:0]  spine_inject_data,\n"
    s += "    output wire        spine_inject_valid,\n"
    s += "    output wire        spine_inject_sop,\n"
    s += "    output wire        spine_inject_eop,\n"
    s += "    input  wire        spine_inject_ready,\n"
    s += "    output wire [1:0]  spine_inject_vc,\n"
    s += "    input  wire [7:0]  spine_extract_data,\n"
    s += "    input  wire        spine_extract_valid,\n"
    s += "    input  wire        spine_extract_sop,\n"
    s += "    input  wire        spine_extract_eop,\n"
    s += "    input  wire [1:0]  spine_extract_vc,\n"
    s += irq_port
    s += "    output wire        boot_done\n"
    s += ");\n"
    s += "    orchestrator #(.ROLE(%d), " % role
    s += params_conn
    s += ") u (\n"
    s += "        .clk(clk), .rst_n(rst_n),\n"
    s += "        .uart_rx(uart_rx), .uart_tx(uart_tx),\n"
    s += (PCIE_CONN if pcie else PCIE_TIE)
    s += "        .topology_rdy(topology_rdy),\n"
    s += SPINE_CONN
    s += "        " + irq_conn + "\n"
    s += "        .boot_done(boot_done), .dispatches(),\n"
    s += "        .weight_flits(), .errors());\n"
    s += "endmodule\n"
    return s


def main():
    open(os.path.join(HERE, "orchestrator.v"), "w").write(gen_orchestrator())
    print("wrote orchestrator.v")

    w = {"orchestrator_chip.v": wrapper_chip()}
    w["orchestrator_mcu.v"] = wrapper_soc(
        "orchestrator_mcu", 1,
        "    parameter CLK_FREQ    = 50_000_000,\n"
        "    parameter BAUD_RATE   = 115200,\n"
        "    parameter NUM_LAYERS  = 2,\n"
        "    parameter BOARD_X     = 4,\n"
        "    parameter BOARD_Y     = 4,\n"
        "    parameter NUM_NODES   = NUM_LAYERS * BOARD_X * BOARD_Y\n",
        ".CLK_FREQ(CLK_FREQ), .BAUD_RATE(BAUD_RATE), .NUM_LAYERS(NUM_LAYERS), "
        ".BOARD_X(BOARD_X), .BOARD_Y(BOARD_Y), .NUM_NODES(NUM_NODES)",
        False, "[7:0]")
    w["orchestrator_sbc.v"] = wrapper_soc(
        "orchestrator_sbc", 2,
        "    parameter CLK_FREQ     = 100_000_000,\n"
        "    parameter BAUD_RATE    = 115200,\n"
        "    parameter NUM_LAYERS   = 8,\n"
        "    parameter BOARD_X      = 8,\n"
        "    parameter BOARD_Y      = 8,\n"
        "    parameter NUM_NODES    = NUM_LAYERS * BOARD_X * BOARD_Y,\n"
        "    parameter DRAM_WORDS   = 1048576,\n"
        "    parameter DRAM_LATENCY = 4,\n"
        "    parameter SRAM_WORDS   = 131072\n",
        ".CLK_FREQ(CLK_FREQ), .BAUD_RATE(BAUD_RATE), .NUM_LAYERS(NUM_LAYERS), "
        ".BOARD_X(BOARD_X), .BOARD_Y(BOARD_Y), .NUM_NODES(NUM_NODES), "
        ".DRAM_WORDS(DRAM_WORDS), .DRAM_LATENCY(DRAM_LATENCY), .SRAM_WORDS(SRAM_WORDS)",
        False, "[15:0]")
    w["orchestrator_sbc_moe.v"] = wrapper_soc(
        "orchestrator_sbc_moe", 3,
        "    parameter CLK_FREQ        = 100_000_000,\n"
        "    parameter BAUD_RATE       = 115200,\n"
        "    parameter NUM_LAYERS      = 8,\n"
        "    parameter BOARD_X         = 8,\n"
        "    parameter BOARD_Y         = 8,\n"
        "    parameter NUM_NODES       = NUM_LAYERS * BOARD_X * BOARD_Y,\n"
        "    parameter MAX_EXPERTS     = 128,\n"
        "    parameter TOP_K           = 8,\n"
        "    parameter HIDDEN_SIZE     = 2816,\n"
        "    parameter GATING_ENTRIES  = 32768,\n"
        "    parameter DRAM_WORDS      = 262144,\n"
        "    parameter DRAM_LATENCY    = 4,\n"
        "    parameter ARRAY_SIZE      = 16\n",
        ".CLK_FREQ(CLK_FREQ), .BAUD_RATE(BAUD_RATE), .NUM_LAYERS(NUM_LAYERS), "
        ".BOARD_X(BOARD_X), .BOARD_Y(BOARD_Y), .NUM_NODES(NUM_NODES), "
        ".MAX_EXPERTS(MAX_EXPERTS), .TOP_K(TOP_K), .HIDDEN_SIZE(HIDDEN_SIZE), "
        ".GATING_ENTRIES(GATING_ENTRIES), .DRAM_WORDS(DRAM_WORDS), "
        ".DRAM_LATENCY(DRAM_LATENCY), .ARRAY_SIZE(ARRAY_SIZE)",
        True, "[15:0]")

    for name, text in w.items():
        open(os.path.join(HERE, name), "w").write(text)
        print("wrote %s" % name)


if __name__ == "__main__":
    main()
