#!/usr/bin/env python3
"""Generate arith_unit.v by folding the per-format FMA/ALU datapaths.

The datapath bodies are extracted verbatim from the existing module files and
placed (with minimal, mechanical identifier renames) inside generate branches
selected by the CU parameter.  The legacy module files become thin wrappers.

Run from this directory:  python3 gen_arith_unit.py
"""
import re
import os
import subprocess

HERE = os.path.dirname(os.path.abspath(__file__))


def body_of(path):
    # Read the ORIGINAL datapath from git HEAD, not the working tree: this
    # script overwrites each source file with a thin wrapper, so a second run
    # would otherwise splice the wrapper into itself (a degenerate arith_unit).
    # Matches the idempotent pattern in HDL/gen_orchestrator.py.
    try:
        src = subprocess.check_output(
            ["git", "show", "HEAD:HDL/core/" + path],
            cwd=HERE, stderr=subprocess.DEVNULL).decode()
    except Exception:
        src = open(os.path.join(HERE, path)).read()
    m = re.search(r"\n\);\s*\n", src)   # port list closes with ');' on its own line
    body = src[m.end():]
    body = body[:body.rindex("endmodule")]
    return body.strip("\n")


def rename(body, subs):
    for pat, repl in subs:
        body = re.sub(pat, repl, body)
    return body


def rename_after_instance(body, inst_pattern, inst_text, subs):
    """Replace a sub-unit instance with a placeholder, apply renames, then
    splice the real instance text back (so its bare .a/.b/.result port names
    are not touched by the renames)."""
    body = re.sub(inst_pattern, "@@FMA_INST@@", body, flags=re.S)
    body = rename(body, subs)
    return body.replace("@@FMA_INST@@", inst_text)


def main():
    out = []
    out.append("`timescale 1ns/1ps")
    out.append("")
    out.append("// =============================================================================")
    out.append("// arith_unit — parameterized FMA / ALU / MAC family")
    out.append("//")
    out.append("// One module; the CU parameter selects the datapath.  The legacy")
    out.append("// modules (bf16/fp16/fp32/fp64 FMA, fp32/fp64/int8 ALU, int8/int4/fp4 MAC")
    out.append("// — MXFP4 is fp4 with a block-scale wshift, CU 7) are thin wrappers around")
    out.append("// this module so their module names, ports and testbenches are unchanged.")
    out.append("// CU 11 is the BitNet b1.58 ternary select-add accumulator (ternary_acc):")
    out.append("// an inline body — it has no legacy source module — also wrapped for its name.")
    out.append("// Generated by gen_arith_unit.py — regenerate, do not hand-edit this file.")
    out.append("// =============================================================================")
    out.append("")
    out.append("module arith_unit #(")
    out.append("    parameter CU = 0")
    out.append(") (")
    out.append("    input  wire        clk,")
    out.append("    input  wire        rst_n,")
    out.append("    input  wire [63:0] a,")
    out.append("    input  wire [63:0] b,")
    out.append("    input  wire [63:0] c,")
    out.append("    input  wire        valid_in,")
    out.append("    input  wire [2:0]  op,")
    out.append("    input  wire        pack_select,")
    out.append("    input  wire        b_pack_select,")
    out.append("    input  wire [3:0]  wshift,")
    out.append("    output wire [63:0] result,")
    out.append("    output wire        valid_out,")
    out.append("    output wire        busy")
    out.append(");")
    out.append("")
    out.append("    localparam CU_BF16_FMA = 0;")
    out.append("    localparam CU_FP16_FMA = 1;")
    out.append("    localparam CU_FP32_FMA = 2;")
    out.append("    localparam CU_FP64_FMA = 3;")
    out.append("    localparam CU_INT8_MAC = 4;")
    out.append("    localparam CU_INT4_MAC = 5;")
    out.append("    localparam CU_FP4_MAC  = 6;")
    out.append("    localparam CU_MXFP4    = 7;")
    out.append("    localparam CU_FP32_ALU = 8;")
    out.append("    localparam CU_FP64_ALU = 9;")
    out.append("    localparam CU_INT8_ALU = 10;")
    out.append("    localparam CU_TERNARY  = 11;")
    out.append("")
    out.append("    generate")

    # ---- CUs 0..2: fma_core wrappers (unchanged core) ------------------------
    fma_core = (
        "            wire [{w1}:0] r; wire rv;\n"
        "            fma_core #(.W({w}), .E({e}), .M({m}), .B({bias}), .AW({aw}), .FTZ({ftz})) u_core (\n"
        "                .clk(clk), .rst_n(rst_n),\n"
        "                .a(a[{w1}:0]), .b(b[{w1}:0]), .c(c[{w1}:0]),\n"
        "                .valid_in(valid_in), .result(r), .valid_out(rv));\n"
        "            assign result = {{{pad}r}};\n"
        "            assign valid_out = rv;\n"
        "            assign busy = 1'b0;\n"
    )
    for name, w, e, m, bias, aw, ftz in [
        ("CU_BF16_FMA", 16, 8, 7, 127, 24, 0),
        ("CU_FP16_FMA", 16, 5, 10, 15, 22, 1),
        ("CU_FP32_FMA", 32, 8, 23, 127, 48, 0),
    ]:
        inner = fma_core.format(
            w=w, w1=w - 1, e=e, m=m, bias=bias, aw=aw, ftz=ftz,
            pad="" if w == 64 else f"{64 - w}'d0, ")
        out.append(f"        if (CU == {name}) begin : g_{name.lower()}\n{inner}        end\n")

    # ---- CU3: fp64_fma body --------------------------------------------------
    b = body_of("fp64_fma.v")
    b = rename(b, [(r"\bresult\b", "r64"), (r"\bvalid_out\b", "v64")])
    inner = (
        "            reg [63:0] r64; reg v64;\n"
        + "\n".join("    " + ln for ln in b.splitlines()) + "\n"
    )
    out.append(f"        if (CU == CU_FP64_FMA) begin : g_fp64_fma\n{inner}"
               "            assign result = r64;\n"
               "            assign valid_out = v64;\n"
               "            assign busy = 1'b0;\n"
               "        end\n")

    # ---- CU4..7: integer / fp4 MAC bodies -----------------------------------
    def mac_body(path, adapt_a=True, adapt_b=True, adapt_c=True, pack=True):
        b = body_of(path)
        subs = []
        if adapt_a:
            subs.append((r"\ba\b", "a8"))
        if adapt_b:
            subs.append((r"\bb\b", "b8"))
        if adapt_c:
            subs.append((r"\bc\b", "c32"))
        subs += [(r"\bresult\b", "r32"), (r"\bvalid_out\b", "v32")]
        b = rename(b, subs)
        decl = "            reg [31:0] r32; reg v32;\n"
        if adapt_a:
            decl += "            wire [7:0] a8 = a[7:0];\n"
        if adapt_b:
            decl += "            wire [7:0] b8 = b[7:0];\n"
        if adapt_c:
            decl += "            wire [31:0] c32 = c[31:0];\n"
        inner = decl + "\n".join("    " + ln for ln in b.splitlines()) + "\n"
        return inner

    for name, path in [("CU_INT8_MAC", "int8_mac.v"),
                       ("CU_INT4_MAC", "int4_mac.v"),
                       ("CU_FP4_MAC", "fp4_mac.v"),
                       ("CU_MXFP4", "fp4_mac.v")]:
        inner = mac_body(path)
        out.append(f"        if (CU == {name}) begin : g_{name.lower()}\n{inner}"
                   "            assign result = {32'd0, r32};\n"
                   "            assign valid_out = v32;\n"
                   "            assign busy = 1'b0;\n"
                   "        end\n")

    # ---- CU8: fp32_alu body --------------------------------------------------
    b = body_of("fp32_alu.v")
    b = rename_after_instance(
        b, r"fp32_fma u_fma\s*\(.*?\);",
        "arith_unit #(.CU(CU_FP32_FMA)) u_fma (\n"
        "            .clk(clk), .rst_n(rst_n),\n"
        "            .a(fma_a), .b(fma_b), .c(fma_c),\n"
        "            .op(3'd0), .valid_in(fma_valid),\n"
        "            .result(fma_result), .valid_out(fma_valid_out));",
        [(r"\ba\b", "a32"), (r"\bb\b", "b32"),
         (r"\bresult\b", "r32"), (r"\bvalid_out\b", "v32"),
         (r"\bbusy\b", "busy8")])
    inner = ("            reg [31:0] r32; reg v32; wire busy8;\n"
             "            wire [31:0] a32 = a[31:0];\n"
             "            wire [31:0] b32 = b[31:0];\n"
             + "\n".join("    " + ln for ln in b.splitlines()) + "\n")
    out.append(f"        if (CU == CU_FP32_ALU) begin : g_fp32_alu\n{inner}"
               "            assign result = {32'd0, r32};\n"
               "            assign valid_out = v32;\n"
               "            assign busy = busy8;\n"
               "        end\n")

    # ---- CU9: fp64_alu body --------------------------------------------------
    b = body_of("fp64_alu.v")
    b = rename_after_instance(
        b, r"fp64_fma u_fma\s*\(.*?\);",
        "arith_unit #(.CU(CU_FP64_FMA)) u_fma (\n"
        "            .clk(clk), .rst_n(rst_n),\n"
        "            .a(fma_a_reg), .b(fma_b_reg), .c(fma_c_reg),\n"
        "            .valid_in(fma_valid_in),\n"
        "            .result(fma_result), .valid_out(fma_valid_out));",
        [(r"\bresult\b", "r64"), (r"\bvalid_out\b", "v64"),
         (r"\bbusy\b", "busy8")])
    inner = ("            reg [63:0] r64; reg v64; wire busy8;\n"
             + "\n".join("    " + ln for ln in b.splitlines()) + "\n")
    out.append(f"        if (CU == CU_FP64_ALU) begin : g_fp64_alu\n{inner}"
               "            assign result = r64;\n"
               "            assign valid_out = v64;\n"
               "            assign busy = busy8;\n"
               "        end\n")

    # ---- CU10: int8_alu body -------------------------------------------------
    b = body_of("int8_alu.v")
    b = rename(b, [(r"\ba\b", "a8"), (r"\bb\b", "b8"),
                   (r"\bresult\b", "r16"), (r"\bvalid_out\b", "v16")])
    inner = ("            reg [15:0] r16; reg v16;\n"
             "            wire [7:0] a8 = a[7:0];\n"
             "            wire [7:0] b8 = b[7:0];\n"
             + "\n".join("    " + ln for ln in b.splitlines()) + "\n")
    out.append(f"        if (CU == CU_INT8_ALU) begin : g_int8_alu\n{inner}"
               "            assign result = {48'd0, r16};\n"
               "            assign valid_out = v16;\n"
               "            assign busy = 1'b0;\n"
               "        end\n")

    # ---- CU11: ternary select-add accumulator (BitNet b1.58) ----------------
    # Inlined (no legacy source file): the {-1,0,+1} weight makes the multiply
    # a signed conditional add, so this is an accumulator with no multiplier.
    # Two-stage pipeline, same shape as the INT8 MAC body above.
    out.append(
        "        if (CU == CU_TERNARY) begin : g_ternary_acc\n"
        "            reg [31:0] r32; reg v32;\n"
        "            wire [7:0] a8 = a[7:0];\n"
        "            wire [7:0] b8 = b[7:0];\n"
        "            wire [31:0] c32 = c[31:0];\n"
        "            wire signed [7:0]  a_s   = a8;\n"
        "            wire signed [31:0] a_ext = {{24{a_s[7]}}, a_s};\n"
        "            wire signed [31:0] prod  = (b8[1:0] == 2'b01) ?  a_ext :\n"
        "                                       (b8[1:0] == 2'b10) ? -a_ext : 32'sd0;\n"
        "            reg signed [31:0] s1_prod;\n"
        "            reg signed [31:0] s1_c;\n"
        "            reg               s1_valid;\n"
        "            always @(posedge clk or negedge rst_n) begin\n"
        "                if (!rst_n) begin\n"
        "                    s1_prod <= 32'sd0;\n"
        "                    s1_c    <= 32'sd0;\n"
        "                    s1_valid <= 1'b0;\n"
        "                end else begin\n"
        "                    s1_prod  <= prod;\n"
        "                    s1_c     <= $signed(c32);\n"
        "                    s1_valid <= valid_in;\n"
        "                end\n"
        "            end\n"
        "            always @(posedge clk or negedge rst_n) begin\n"
        "                if (!rst_n) begin\n"
        "                    r32 <= 32'd0; v32 <= 1'b0;\n"
        "                end else begin\n"
        "                    r32 <= s1_prod + s1_c; v32 <= s1_valid;\n"
        "                end\n"
        "            end\n"
        "            assign result = {32'd0, r32};\n"
        "            assign valid_out = v32;\n"
        "            assign busy = 1'b0;\n"
        "        end\n")
    out.append("    endgenerate")
    out.append("")
    out.append("endmodule")

    open(os.path.join(HERE, "arith_unit.v"), "w").write("\n".join(out) + "\n")
    print("wrote arith_unit.v")

    for name, text in wrappers().items():
        open(os.path.join(HERE, name), "w").write(text)
        print("wrote %s" % name)


def wrappers():
    """Thin wrapper modules preserving the legacy names/ports."""
    hdr = ("`timescale 1ns/1ps\n"
           "// %s — thin wrapper over arith_unit (folded FMA/ALU/MAC family).\n"
           "// Generated by gen_arith_unit.py.\n")
    fma = (hdr + "module %s (\n"
           "    input  wire         clk,\n"
           "    input  wire         rst_n,\n"
           "    input  wire [%d:0]  a,\n"
           "    input  wire [%d:0]  b,\n"
           "    input  wire [%d:0]  c,\n"
           "    input  wire         valid_in,\n"
           "    output wire [%d:0]  result,\n"
           "    output wire         valid_out\n"
           ");\n"
           "    wire [63:0] r; wire v; wire bsy;\n"
           "    arith_unit #(.CU(%d)) u_core (\n"
           "        .clk(clk), .rst_n(rst_n),\n"
           "        .a(%s), .b(%s), .c(%s),\n"
           "        .valid_in(valid_in), .op(3'd0), .pack_select(1'b0),\n"
           "        .b_pack_select(1'b0), .wshift(4'd0),\n"
           "        .result(r), .valid_out(v), .busy(bsy));\n"
           "    assign result = r[%d:0];\n"
           "    assign valid_out = v;\n"
           "endmodule\n")

    def pad(w):
        return (lambda x, w=w: x if w == 64 else "{%d'd0, %s}" % (64 - w, x))

    w = {}
    for mod, cu, bw in [("bf16_fma", 0, 16), ("fp16_fma", 1, 16),
                        ("fp32_fma", 2, 32), ("fp64_fma", 3, 64)]:
        w[mod + ".v"] = fma % (mod, mod, bw - 1, bw - 1, bw - 1, bw - 1, cu,
                               pad(bw)("a"), pad(bw)("b"), pad(bw)("c"), bw - 1)

    mac = (hdr + "module %s (\n"
           "    input  wire        clk,\n"
           "    input  wire        rst_n,\n"
           "    input  wire [7:0]  a,\n"
           "%s"
           "    input  wire [7:0]  b,\n"
           "%s"
           "    input  wire [31:0] c,\n"
           "%s"
           "    input  wire        valid_in,\n"
           "    output wire [31:0] result,\n"
           "    output wire        valid_out\n"
           ");\n"
           "    wire [63:0] r; wire v; wire bsy;\n"
           "    arith_unit #(.CU(%d)) u_core (\n"
           "        .clk(clk), .rst_n(rst_n),\n"
           "        .a({56'd0, a}), .b({56'd0, b}), .c({32'd0, c}),\n"
           "        .valid_in(valid_in), .op(3'd0), %s\n"
           "        %s %s\n"
           "        .result(r), .valid_out(v), .busy(bsy));\n"
           "    assign result = r[31:0];\n"
           "    assign valid_out = v;\n"
           "endmodule\n")

    def psel(need):
        return "    input  wire        pack_select,\n" if need else ""

    def bsel(need):
        return "    input  wire        b_pack_select,\n" if need else ""

    def wsh(need):
        return "    input  wire [3:0]  wshift,\n" if need else ""

    w["int8_mac.v"] = mac % ("int8_mac", "int8_mac", "", "", "", 4,
                             ".pack_select(1'b0),", ".b_pack_select(1'b0),", ".wshift(4'd0),")
    w["ternary_acc.v"] = mac % ("ternary_acc", "ternary_acc", "", "", "", 11,
                                ".pack_select(1'b0),", ".b_pack_select(1'b0),", ".wshift(4'd0),")
    w["int4_mac.v"] = mac % ("int4_mac", "int4_mac", psel(1), bsel(1), "", 5,
                             ".pack_select(pack_select),", ".b_pack_select(b_pack_select),",
                             ".wshift(4'd0),")
    w["fp4_mac.v"] = mac % ("fp4_mac", "fp4_mac", psel(1), bsel(1), wsh(1), 6,
                            ".pack_select(pack_select),", ".b_pack_select(b_pack_select),",
                            ".wshift(wshift),")

    alu = (hdr + "module %s (\n"
           "    input  wire         clk,\n"
           "    input  wire         rst_n,\n"
           "    input  wire [%d:0]  a,\n"
           "    input  wire [%d:0]  b,\n"
           "    input  wire         valid_in,\n"
           "    input  wire [2:0]   op,\n"
           "    output wire [%d:0]  result,\n"
           "    output wire         valid_out,\n"
           "    output wire         busy\n"
           ");\n"
           "    wire [63:0] r; wire v; wire bsy;\n"
           "    arith_unit #(.CU(%d)) u_core (\n"
           "        .clk(clk), .rst_n(rst_n),\n"
           "        .a(%s), .b(%s), .c(64'd0),\n"
           "        .valid_in(valid_in), .op(op), .pack_select(1'b0),\n"
           "        .b_pack_select(1'b0), .wshift(4'd0),\n"
           "        .result(r), .valid_out(v), .busy(busy));\n"
           "    assign result = r[%d:0];\n"
           "    assign valid_out = v;\n"
           "endmodule\n")
    w["fp32_alu.v"] = alu % ("fp32_alu", "fp32_alu", 31, 31, 31, 8,
                             pad(32)("a"), pad(32)("b"), 31)
    w["fp64_alu.v"] = alu % ("fp64_alu", "fp64_alu", 63, 63, 63, 9, "a", "b", 63)

    w["int8_alu.v"] = (hdr + "module int8_alu (\n"
                       "    input  wire        clk,\n"
                       "    input  wire        rst_n,\n"
                       "    input  wire signed [7:0] a,\n"
                       "    input  wire signed [7:0] b,\n"
                       "    input  wire        valid_in,\n"
                       "    input  wire [2:0]  op,\n"
                       "    output wire [15:0] result,\n"
                       "    output wire        valid_out\n"
                       ");\n"
                       "    wire [63:0] r; wire v; wire bsy;\n"
                       "    arith_unit #(.CU(10)) u_core (\n"
                       "        .clk(clk), .rst_n(rst_n),\n"
                       "        .a({56'd0, a}), .b({56'd0, b}), .c(64'd0),\n"
                       "        .valid_in(valid_in), .op(op), .pack_select(1'b0),\n"
                       "        .b_pack_select(1'b0), .wshift(4'd0),\n"
                       "        .result(r), .valid_out(v), .busy(bsy));\n"
                       "    assign result = r[15:0];\n"
                       "    assign valid_out = v;\n"
                       "endmodule\n")
    return w


if __name__ == "__main__":
    main()
